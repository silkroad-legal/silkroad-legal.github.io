/* ---------- i18n ---------- */
const RU = {};
const i18nNodes = document.querySelectorAll("[data-i18n]");
i18nNodes.forEach((el) => {
  const key = el.dataset.i18n;
  if (!(key in RU)) RU[key] = el.innerHTML;
});
const DICT = { ru: RU, en: EN };

let lang = "ru";

function t(key) {
  return (DICT[lang] && DICT[lang][key]) ?? RU[key] ?? "";
}

function storeLang(value) {
  try { localStorage.setItem("srla-lang", value); } catch (e) { /* storage недоступен */ }
}
function readLang() {
  const q = new URLSearchParams(location.search).get("lang");
  if (q === "ru" || q === "en") return q;
  try {
    const saved = localStorage.getItem("srla-lang");
    if (saved === "ru" || saved === "en") return saved;
  } catch (e) { /* storage недоступен */ }
  return (navigator.language || "ru").toLowerCase().startsWith("ru") ? "ru" : "en";
}

function setLang(next) {
  lang = next;
  document.documentElement.lang = next;
  i18nNodes.forEach((el) => { el.innerHTML = t(el.dataset.i18n); });
  document.querySelectorAll(".lang button").forEach((b) => {
    b.setAttribute("aria-pressed", String(b.dataset.lang === next));
  });
  document.title = META[next].title;
  document.querySelector('meta[name="description"]').content = META[next].description;
  document.querySelectorAll("[data-close]").forEach((b) => b.setAttribute("aria-label", META[next].close));
  if (profileDialog.open && currentProfile) renderProfile(currentProfile);
  if (qrDialog.open && currentQrName) qrName.innerHTML = t(currentQrName);
  storeLang(next);
}

document.querySelectorAll(".lang button").forEach((b) => {
  b.addEventListener("click", () => setLang(b.dataset.lang));
});

